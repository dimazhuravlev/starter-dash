/** Сокращает адрес заказа: заменяет полные названия типов улиц и городских объектов
 *  на аббревиатуры, убирает название города в конце строки */
export function formatAddress(address: string): string {
  // JS \b не поддерживает Unicode, поэтому граница слова через кириллицу
  const cyr = '[а-яёА-ЯЁ]'
  const w = (word: string) => new RegExp(`(?<!${cyr})(?:${word})(?!${cyr})`, 'gi')

  const ABBR: [RegExp, string][] = [
    [w('улица'),           'ул.'],
    [w('проспект'),        'пр-т'],
    [w('переулок'),        'пер.'],
    [w('набережная'),      'наб.'],
    [w('шоссе'),           'ш.'],
    [w('бульвар'),         'б-р'],
    [w('тупик'),           'туп.'],
    [w('площадь'),         'пл.'],
    [w('аллея'),           'ал.'],
    [w('проезд'),          'пр-д'],
    [w('тракт'),           'тр.'],
    [w('линия'),           'лин.'],
    [w('микрорайон'),      'мкр-н'],
    [w('квартал'),         'кв-л'],
    [w('посёлок|поселок'), 'пос.'],
  ]

  let result = address
  for (const [pattern, abbr] of ABBR) {
    result = result.replace(pattern, abbr)
  }

  // Удаляем город в конце: с маркером «г.» / «город» или без —
  // последний сегмент после запятой, который не содержит цифр, 1–3 слова с заглавной буквы
  result = result.replace(
    /,\s*(?:(?:г\.|город)\s+)?[А-ЯЁ][а-яёА-ЯЁ-]*(?:\s+[А-ЯЁа-яё][а-яёА-ЯЁ-]*){0,2}\s*$/,
    '',
  )

  return result.trim()
}
